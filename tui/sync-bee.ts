// Syncs bee-cli to the tip of its default branch, then bakes the SHA
// into src/bee-sha.ts (gitignored, generated). Policy:
//   - vendor/ is read-only: any local modification aborts BEFORE the reset.
//   - network unreachable -> throws -> build dies. No stale binaries, no
//     overrides. Every queen binary embeds the latest bee-cli or none at all.
import { $ } from "bun";

const VENDOR = new URL("./bee-cli", import.meta.url).pathname;
const SHA_FILE = new URL("./src/bee-sha.ts", import.meta.url).pathname;

async function git(...args: string[]): Promise<string> {
  const out = await $`git -C ${VENDOR} ${args}`.text();
  return out.trim();
}

export async function syncBee(): Promise<string> {
  // Resolve the default branch via origin/HEAD (set up by the submodule clone).
  const headRef = await git("symbolic-ref", "refs/remotes/origin/HEAD");
  const branch = headRef.replace("refs/remotes/origin/", "");
  if (!branch || branch.includes("/")) throw new Error(`cannot resolve origin/HEAD (got ${headRef})`);

  const dirty = await git("status", "--porcelain");
  if (dirty) {
    throw new Error(
      `bee-cli has local modifications (read-only by policy) — discard them first:\n${dirty}`,
    );
  }

  const oldSha = await git("rev-parse", "HEAD");
  await git("fetch", "--depth", "1", "origin", branch);
  await git("reset", "--hard", `origin/${branch}`);
  const newSha = await git("rev-parse", "HEAD");

  if (oldSha === newSha) {
    console.log(`bee-cli: already at ${newSha.slice(0, 12)}`);
  } else {
    console.log(`bee-cli: ${oldSha.slice(0, 12)} -> ${newSha.slice(0, 12)}`);
    const log = await git("log", "--oneline", `${oldSha}..${newSha}`);
    if (log) console.log(log);
  }

  await Bun.write(SHA_FILE, `// GENERATED by sync-bee.ts — do not edit.\nexport const BEE_CLI_SHA = "${newSha}";\n`);
  return newSha;
}

if (import.meta.main) {
  await syncBee();
}
